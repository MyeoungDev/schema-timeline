CREATE TABLE returns (
    return_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   NUMBER NOT NULL REFERENCES orders(order_id),
    reason     VARCHAR2(400),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE return_lines (
    return_id NUMBER NOT NULL REFERENCES returns(return_id) ON DELETE CASCADE,
    order_id  NUMBER NOT NULL,
    line_no   NUMBER(4) NOT NULL,
    quantity  NUMBER(6) NOT NULL,
    CONSTRAINT pk_return_lines PRIMARY KEY (return_id, order_id, line_no),
    CONSTRAINT fk_return_lines_line FOREIGN KEY (order_id, line_no) REFERENCES order_lines(order_id, line_no)
);
