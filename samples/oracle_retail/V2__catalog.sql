CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   NUMBER REFERENCES categories(category_id),
    name        VARCHAR2(100) NOT NULL
);

CREATE TABLE suppliers (
    supplier_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(150) NOT NULL,
    country_code CHAR(2) REFERENCES countries(country_code)
);
COMMENT ON TABLE suppliers IS 'Product suppliers';

CREATE TABLE products (
    product_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER NOT NULL REFERENCES categories(category_id),
    supplier_id NUMBER REFERENCES suppliers(supplier_id),
    sku         VARCHAR2(20) NOT NULL,
    name        VARCHAR2(200) NOT NULL,
    legacy_code VARCHAR2(10),
    CONSTRAINT uq_products_sku UNIQUE (sku)
);
COMMENT ON TABLE products IS 'Sellable products';

CREATE TABLE product_prices (
    product_id    NUMBER NOT NULL REFERENCES products(product_id),
    currency_code CHAR(3) NOT NULL REFERENCES currencies(currency_code),
    amount        NUMBER(10,2) NOT NULL,
    valid_from    DATE NOT NULL,
    CONSTRAINT pk_product_prices PRIMARY KEY (product_id, currency_code, valid_from)
);
