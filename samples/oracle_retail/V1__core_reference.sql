CREATE TABLE countries (
    country_code CHAR(2) PRIMARY KEY,
    name         VARCHAR2(80) NOT NULL
);
COMMENT ON TABLE countries IS 'ISO country codes';

CREATE TABLE currencies (
    currency_code CHAR(3) PRIMARY KEY,
    name          VARCHAR2(50) NOT NULL,
    minor_units   NUMBER(1) DEFAULT 2 NOT NULL
);

CREATE TABLE departments (
    department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL,
    cost_center   VARCHAR2(20)
);

CREATE TABLE employees (
    employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id NUMBER NOT NULL REFERENCES departments(department_id),
    full_name     VARCHAR2(120) NOT NULL,
    email         VARCHAR2(200),
    hired_on      DATE DEFAULT SYSDATE NOT NULL
);
COMMENT ON TABLE employees IS 'Staff members';

CREATE TABLE customers (
    customer_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR2(200) NOT NULL,
    full_name    VARCHAR2(120) NOT NULL,
    phone        VARCHAR2(30),
    fax          VARCHAR2(30),
    country_code CHAR(2) REFERENCES countries(country_code),
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_customers_email UNIQUE (email)
);
COMMENT ON TABLE customers IS 'Registered customers';

CREATE TABLE customer_addresses (
    address_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  NUMBER NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    line1        VARCHAR2(200) NOT NULL,
    city         VARCHAR2(100) NOT NULL,
    postal_code  VARCHAR2(20),
    country_code CHAR(2) NOT NULL REFERENCES countries(country_code)
);

CREATE TABLE legacy_fax_log (
    log_id      NUMBER PRIMARY KEY,
    customer_id NUMBER REFERENCES customers(customer_id),
    sent_at     DATE
);
COMMENT ON TABLE legacy_fax_log IS 'Outbound fax log from the old system';
