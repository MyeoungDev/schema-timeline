CREATE TABLE warehouses (
    warehouse_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR2(10) NOT NULL UNIQUE,
    country_code CHAR(2) NOT NULL REFERENCES countries(country_code)
);

CREATE TABLE stock_levels (
    warehouse_id NUMBER NOT NULL REFERENCES warehouses(warehouse_id),
    product_id   NUMBER NOT NULL REFERENCES products(product_id),
    on_hand      NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_stock_levels PRIMARY KEY (warehouse_id, product_id)
);

CREATE TABLE stock_movements (
    movement_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id NUMBER NOT NULL REFERENCES warehouses(warehouse_id),
    product_id   NUMBER NOT NULL REFERENCES products(product_id),
    quantity     NUMBER(10) NOT NULL,
    moved_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_stock_movements_product ON stock_movements (product_id, moved_at);
