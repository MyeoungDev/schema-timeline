CREATE TABLE carriers (
    carrier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(100) NOT NULL
);

CREATE TABLE shipments (
    shipment_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     NUMBER NOT NULL REFERENCES orders(order_id),
    carrier_id   NUMBER REFERENCES carriers(carrier_id),
    warehouse_id NUMBER NOT NULL REFERENCES warehouses(warehouse_id),
    tracking_no  VARCHAR2(40),
    shipped_at   TIMESTAMP
);
COMMENT ON TABLE shipments IS 'Outbound shipments';

CREATE TABLE shipment_items (
    shipment_id NUMBER NOT NULL REFERENCES shipments(shipment_id) ON DELETE CASCADE,
    order_id    NUMBER NOT NULL,
    line_no     NUMBER(4) NOT NULL,
    quantity    NUMBER(6) NOT NULL,
    CONSTRAINT pk_shipment_items PRIMARY KEY (shipment_id, order_id, line_no),
    CONSTRAINT fk_shipment_items_line FOREIGN KEY (order_id, line_no) REFERENCES order_lines(order_id, line_no)
);
